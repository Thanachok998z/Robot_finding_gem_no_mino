import cv2


# ==========================================
# ตัวแปรเก็บตำแหน่งที่คลิก
# ==========================================

click_x = -1
click_y = -1


# ==========================================
# ฟังก์ชันเมื่อคลิกเมาส์
# ==========================================

def mouse_callback(event, x, y, flags, param):

    global click_x, click_y

    if event == cv2.EVENT_LBUTTONDOWN:

        click_x = x
        click_y = y

        print(f"\nตำแหน่งที่คลิก: ({x}, {y})")


# ==========================================
# เปิดกล้อง
# ==========================================

cap = cv2.VideoCapture(2)

if not cap.isOpened():
    print("ไม่สามารถเปิดกล้อง index 2 ได้")
    exit()


# ==========================================
# สร้างหน้าต่าง
# ==========================================

window_name = "Camera"

cv2.namedWindow(window_name)

cv2.setMouseCallback(
    window_name,
    mouse_callback
)


print("เปิดกล้องแล้ว")
print("คลิกบนภาพเพื่อดูค่าสี")
print("กด Q เพื่อออก")


# ==========================================
# Real-time
# ==========================================

while True:

    ret, frame = cap.read()

    if not ret:
        print("ไม่สามารถอ่านภาพจากกล้องได้")
        break


    # ======================================
    # แปลง BGR -> HSV
    # ======================================

    hsv = cv2.cvtColor(
        frame,
        cv2.COLOR_BGR2HSV
    )


    # ======================================
    # ถ้ามีการคลิก
    # ======================================

    if click_x >= 0 and click_y >= 0:

        # ------------------------------
        # อ่านค่า BGR
        # ------------------------------

        b, g, r = frame[
            click_y,
            click_x
        ]


        # ------------------------------
        # อ่านค่า HSV
        # ------------------------------

        h, s, v = hsv[
            click_y,
            click_x
        ]


        # ------------------------------
        # แสดงจุดที่คลิก
        # ------------------------------

        cv2.circle(
            frame,
            (click_x, click_y),
            5,
            (0, 0, 255),
            -1
        )


        # ------------------------------
        # แสดงค่า BGR
        # ------------------------------

        cv2.putText(
            frame,
            f"BGR: ({b}, {g}, {r})",
            (click_x + 10, click_y - 30),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.6,
            (255, 255, 255),
            2
        )


        # ------------------------------
        # แสดงค่า HSV
        # ------------------------------

        cv2.putText(
            frame,
            f"HSV: ({h}, {s}, {v})",
            (click_x + 10, click_y),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.6,
            (255, 255, 255),
            2
        )


        # ------------------------------
        # แสดงใน Terminal ด้วย
        # ------------------------------

        print(
            f"Point ({click_x}, {click_y}) | "
            f"BGR=({b},{g},{r}) | "
            f"HSV=({h},{s},{v})"
        )


    # ======================================
    # แสดงภาพ
    # ======================================

    cv2.imshow(
        window_name,
        frame
    )


    # ======================================
    # กด Q เพื่อออก
    # ======================================

    key = cv2.waitKey(1) & 0xFF

    if key == ord("q"):
        break


# ==========================================
# ปิด
# ==========================================

cap.release()

cv2.destroyAllWindows()